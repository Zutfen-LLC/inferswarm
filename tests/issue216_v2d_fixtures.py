"""Issue #216 correction-campaign fixture helpers.

Shared builders for the corrected assembler's synthetic evidence trees:
a faithful fresh-mapping artifact (R3 identity probes revalidating
against RETAINED physical probe bytes), closure/authority bindings, and
the #35-faithful transport raw records. Kept in one module so both the
concurrent and assembler test suites derive identical shapes.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))

import issue216_receipt as rc
